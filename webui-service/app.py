def _normalize_lx_source_list(raw) -> str:
    if isinstance(raw, str):
        text = raw.strip()
        if not text:
            return "[]"
        try:
            items = json.loads(text)
        except Exception as exc:
            raise ValueError(f"LX_SOURCE_LIST: 不是合法的 JSON 数组: {exc}") from exc
    elif isinstance(raw, list):
        items = raw
    else:
        raise ValueError(f"LX_SOURCE_LIST: 期望 JSON 数组，收到 {type(raw).__name__}")

    if not isinstance(items, list):
        raise ValueError("LX_SOURCE_LIST: 期望 JSON 数组，收到 JSON 对象或其他类型")

    normalized: list[dict[str, str]] = []
    seen_urls: set[str] = set()
    for item in items[:50]:  # 上限 50 条
        if not isinstance(item, dict):
            continue
        url = str(item.get("url") or "").strip()
        if not url:
            continue
        url_lower = url.lower()
        if not (url_lower.startswith("http://") or url_lower.startswith("https://") or url_lower.startswith("file://")):
            continue
        if len(url) > 2000:
            continue
        if url in seen_urls:
            continue
        seen_urls.add(url)

        name = str(item.get("name") or "").strip()
        name = re.sub(r"[\r\n\t]+", " ", name).strip()[:80]
        normalized.append({"name": name, "url": url, "active": bool(item.get("active"))})

    return json.dumps(normalized, ensure_ascii=False, separators=(",", ":"))


def _lx_list_items(raw) -> list[dict]:
    """解析 LX_SOURCE_LIST JSON 字符串为 dict 列表（非法输入返回空列表）。"""
    if isinstance(raw, list):
        items = raw
    else:
        try:
            items = json.loads(str(raw or "").strip() or "[]")
        except Exception:
            return []
    if not isinstance(items, list):
        return []
    return [i for i in items if isinstance(i, dict)]


def _list_active_urls(values: dict) -> set[str]:
    """从 .env 值推导激活 URL 集合：优先列表 active 标记；无标记回退 LX_SOURCE_URL 单值（旧数据）。"""
    urls: set[str] = set()
    for item in _lx_list_items(values.get("LX_SOURCE_LIST")):
        if item.get("active"):
            url = str(item.get("url") or "").strip()
            if url:
                urls.add(url)
    if not urls:
        url = str(values.get("LX_SOURCE_URL") or "").strip()
        if url:
            urls.add(url)
    return urls


def _derive_lx_list_actives(items: list[dict], ref_url: str) -> list[dict]:
    """兼容升级：列表无任何 active 标记时按 LX_SOURCE_URL 推导（全部项显式落布尔）。"""
    if items and not any(i.get("active") for i in items):
        for item in items:
            item["active"] = bool(ref_url) and str(item.get("url") or "").strip() == ref_url
    return items


