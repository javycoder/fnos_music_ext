# 飞牛桌面 iframe 不能嵌 http://主机:8774（桌面是 HTTPS，混合内容会被浏览器丢掉，窗口一片空白）。
# 入口改走网关同源路径 /app/fnmusic-ext，这里把该前缀剥掉，直连 :8774 的 /api 不受影响。
DESKTOP_PREFIX = "/app/fnmusic-ext"


class DesktopPrefixMiddleware:
    def __init__(self, app, prefix: str = DESKTOP_PREFIX):
        self.app = app
        self.prefix = prefix

    async def __call__(self, scope, receive, send):
        if scope["type"] in ("http", "websocket"):
            path = scope.get("path") or ""
            if path == self.prefix or path.startswith(self.prefix + "/"):
                scope = dict(scope)
                stripped = path[len(self.prefix):] or "/"
                scope["path"] = stripped
                if isinstance(scope.get("raw_path"), (bytes, bytearray)):
                    scope["raw_path"] = stripped.encode("ascii")
        await self.app(scope, receive, send)


class AuthMiddleware:
    """管理接口要求飞牛网关注入的管理员身份。桌面前缀由外层中间件先剥掉。"""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return
        path = scope.get("path") or ""
        if not path.startswith("/api/") or _is_admin(_header_map(scope)):
            await self.app(scope, receive, send)
            return
        body = '{"ok":false,"error":"需要管理员"}'.encode()
        await send({
            "type": "http.response.start",
            "status": 403,
            "headers": [
                [b"content-type", b"application/json; charset=utf-8"],
                [b"content-length", str(len(body)).encode()],
            ],
        })
        await send({"type": "http.response.body", "body": body})


app.add_middleware(AuthMiddleware)
app.add_middleware(DesktopPrefixMiddleware)


class NoCacheStaticMiddleware:
    """HTML 与静态资源强制协商缓存。

    响应原本只有 etag/last-modified、没有 Cache-Control，飞牛桌面 WebView 与
    浏览器会按启发式缓存沿用旧页面——升级后版本文案（接口）是新的、菜单却
    缺失（新 HTML 没被加载）。no-cache 每次带 etag 回源验证，命中即 304。
    """

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return
        # 无论本中间件位于 DesktopPrefix 内层还是外层，/static/ 子串都能匹配
        no_cache_path = "/static/" in (scope.get("path") or "")

        async def send_wrapper(message):
            if message["type"] == "http.response.start" and (
                    no_cache_path or _is_html(message)):
                message = dict(message)
                message["headers"] = list(message.get("headers", [])) + [
                    [b"cache-control", b"no-cache"],
                ]
            await send(message)

        await self.app(scope, receive, send_wrapper)


def _is_html(message) -> bool:
    for key, value in message.get("headers", []):
        if key.lower() == b"content-type" and value.lower().startswith(b"text/html"):
            return True
    return False


app.add_middleware(NoCacheStaticMiddleware)
