    """可编程的 lxmusic HTTP 桩：healthz 与业务端点分别编排。"""
    state = {
        "healthy": True,        # 探活结果（False 时按 unhealthy_kind 返回）
        # unhealthy_kind: "lxserver" → lxmusic 自报 lxserver 不可达；
        # "unreachable" → lxmusic 自身连不上（应补启整条链路）
        "unhealthy_kind": "unreachable",
        # 补启 N 个进程后转健康（模拟启动生效）；0 表示永不自愈
        "healthy_after_starts": 0,
        "probes": 0,
        "business": {},         # path -> handler
        "calls": [],
    }
    monkeypatch.setitem(webui.CONF, "lx_url", "http://lx.test")

    def handler(request: httpx.Request) -> httpx.Response:
        path = request.url.path
        if path == "/healthz":
            state["probes"] += 1
            healthy = state["healthy"] or (
                state["healthy_after_starts"] and procs["starts"] >= state["healthy_after_starts"])
            if healthy:
                return httpx.Response(200, json={"ok": True})
            if state["unhealthy_kind"] == "unreachable":
                # lxmusic 自身不可达：WebUI 连不上它
                raise httpx.ConnectError("All connection attempts failed", request=request)
            return httpx.Response(503, json={"ok": False, "error": "lxserver unreachable",
                                             "user_source": {"last_error": "lxserver unreachable"}})
        state["calls"].append(path)
        fn = state["business"].get(path)
        if fn is not None:
            return fn(request)
        if path == "/api/v1/source" and request.method == "POST":
            url = json.loads(request.content).get("url", "")
            return httpx.Response(200, json={"ok": True, "source_id": "test-source", "data": {
                "sources": [{"id": "test-source", "url": url, "status": "success"}]}})
        return httpx.Response(200, json={"ok": True})

    webui.app.state.http = httpx.AsyncClient(transport=httpx.MockTransport(handler))
    return state


