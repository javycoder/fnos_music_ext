def test_supervisor_wait_uses_deadline(env_file, procs, lx_http, monkeypatch):
    import asyncio
    import time
    from types import SimpleNamespace
    lx_http["healthy"] = False
    budgets = []
    def slow(*args, timeout):
        budgets.append(timeout)
        time.sleep(0.08)
        return 3, ""
    monkeypatch.setattr(webui, "supervisorctl", slow)
    async def run():
        start = time.monotonic()
        result = await webui._lx_ensure_ready(SimpleNamespace(app=webui.app), timeout=0.03)
        assert result["status"] == 504
