def _install_lx_transport(monkeypatch, handler):
    """给状态页的音源 HTTP 请求安装可编程替身。

    webui 的 get_http() 从 request.state.client 取用，طلب作用域内拿不到时会自建
    客户端，因此这里直接固定 http 客户端，确保替身一定生效。
    """
    monkeypatch.setitem(webui.CONF, "lx_url", "http://lx.test")
    monkeypatch.setattr(webui, "supervisorctl", _fake_supervisorctl())
    client = httpx.AsyncClient(transport=httpx.MockTransport(handler))
    monkeypatch.setattr(webui, "get_http", lambda *args, **kwargs: client)


def _fake_supervisorctl():
    def fake(*args, timeout=20.0):
        if args[0] == "status":
            lines = [
                "lxserver                        RUNNING   pid 1, uptime 0:01:00",
                "lxmusic                         RUNNING   pid 2, uptime 0:01:00",
            ]
            return 3, "\n".join(lines)
        return 0, f"{args[0]}ed {args[1] if len(args) > 1 else ''}"
    return fake


def test_status_reports_layered_health(env_file, log_root, monkeypatch, client):
    """/api/status 要给出分层结论：进程、HTTP、列表、脚本、播放各一层。"""
    def handler(request: httpx.Request) -> httpx.Response:
        if request.url.path == "/healthz":
            return httpx.Response(200, json={"ok": True, "user_source": {
                "state": "ready", "initialized": True, "sources": [
                    {"id": "a", "status": "success", "name": "源A"}],
                "ready_count": 1, "failed_count": 0, "pending_count": 0}})
        return httpx.Response(200, json={"ok": True, "data": {"sources": []}})

    _install_lx_transport(monkeypatch, handler)
    health = client.get("/api/status").json()["health"]
    for layer in ("process", "http", "list", "script", "playback"):
        assert layer in health, f"缺少健康分层：{layer}"
    assert health["process"]["ok"] is True
    assert health["http"]["ok"] is True
    assert health["list"]["ok"] is True
    assert health["script"]["ok"] is True


def test_status_preserves_timeout_error_type(env_file, log_root, monkeypatch, client):
    """#108 现场类型：进程 RUNNING 但查询超时——异常类型必须是 timeout 而非笼统失败。"""
    def handler(request: httpx.Request) -> httpx.Response:
        raise httpx.ReadTimeout("timed out", request=request)

    _install_lx_transport(monkeypatch, handler)
    body = client.get("/api/status").json()
    health = body["health"]
    assert health["process"]["ok"] is True, "supervisor 显示进程仍在运行"
    assert health["http"]["ok"] is False
    assert health["http"]["error_type"] == "timeout", health["http"]
    assert "timed out" in health["http"]["detail"]


