def _export(log_root, export_temp_root, client):
    """导出一次并解出成员内容。"""
    response = client.get("/api/logs/export")
    assert response.status_code == 200, response.text
    with zipfile.ZipFile(io.BytesIO(response.content)) as archive:
        return {name: archive.read(name) for name in archive.namelist()}


# ------------------------------------------------------------- 导出脱敏 --

SECRET = "supersecret-token-value"


@pytest.mark.parametrize("line,leaked", [
    ("GET /api?token=" + SECRET, SECRET),
    ('Authorization: Bearer ' + SECRET, SECRET),
    ('{"cookie": "' + SECRET + '"}', SECRET),
    (f"download https://x/y?key={SECRET}&page=2", SECRET),
    (f"api_key={SECRET}", SECRET),
])
def test_export_redacts_secret_assignments(env_file, log_root, export_temp_root, client,
                                           line, leaked):
    """日志里的密钥/令牌在导出包里必须被打码，不能原样发给下载者。"""
    (log_root / "lxserver.log").write_text(line + "\n", encoding="utf-8")
    members = _export(log_root, export_temp_root, client)
    body = members["lxserver.log"].decode("utf-8")
    assert leaked not in body, f"导出未脱敏：{body!r}"
    assert "***" in body
    assert "lxserver.log" in members


def test_export_keeps_ordinary_diagnostic_text(env_file, log_root, export_temp_root, client):
    """脱敏不能误伤排障信息：普通日志正文要完整保留。"""
    text = "2026-10-31 lxserver listening on 127.0.0.1:8005 request took 12ms\n"
    (log_root / "lxserver.log").write_text(text, encoding="utf-8")
    members = _export(log_root, export_temp_root, client)
    assert members["lxserver.log"].decode("utf-8") == text


def test_export_includes_lxserver_log(env_file, log_root, export_temp_root, client):
    """#108 直接缺口：导出包里要能读到 lxserver 运行日志。"""
    (log_root / "lxserver.log").write_text("lxserver boot\n", encoding="utf-8")
    members = _export(log_root, export_temp_root, client)
    assert members["lxserver.log"] == b"lxserver boot\n"


def test_export_snapshot_is_redacted(env_file, log_root, export_temp_root, client, monkeypatch):
    """环境快照同样要脱敏（它可能包含 config 摘要里的敏感值）。"""
    def snapshot_lines(context="host"):
        return [f"[env] token={SECRET} hostname=fnos other=plain"]
    monkeypatch.setattr(webui, "env_snapshot_lines", snapshot_lines)
    members = _export(log_root, export_temp_root, client)
    body = members["export_env_snapshot.txt"].decode("utf-8")
    assert SECRET not in body
    assert "hostname=fnos" in body and "other=plain" in body


def test_export_redaction_survives_oversized_line(
        env_file, log_root, export_temp_root, client):
    """超长行不能被截断后把秘密尾巴漏出去。"""
    padding = "x" * 5000
    (log_root / "lxserver.log").write_text(f"head {padding} token={SECRET}\n", encoding="utf-8")
    members = _export(log_root, export_temp_root, client)
    assert SECRET not in members["lxserver.log"].decode("utf-8")


