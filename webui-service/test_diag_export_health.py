def test_status_process_layer_down_not_reported_as_http(
        env_file, log_root, monkeypatch, client):
    """进程没起时不伪装成 HTTP 故障，分层要各归各位。"""
    monkeypatch.setitem(webui.CONF, "lx_url", "http://lx.test")

    def fake(*args, timeout=20.0):
        if args[0] == "status":
            return 3, "lxserver                        STOPPED   Not started\n" \
                      "lxmusic                         STOPPED   Not started"
        return 0, ""
    monkeypatch.setattr(webui, "supervisorctl", fake)
    webui.app.state.http = httpx.AsyncClient(
        transport=httpx.MockTransport(lambda request: httpx.Response(200, json={"ok": True})))
    health = client.get("/api/status").json()["health"]
    assert health["process"]["ok"] is False
    assert health["process"]["detail"]
    # 进程层就失败时不再去问 HTTP，避免用旧 Laplacians的答案掩盖真实原因
    assert health["http"]["ok"] is False
    assert health["http"]["error_type"] == "not_probed"


def test_status_layered_health_is_bounded(env_file, log_root, monkeypatch, client):
    """健康检查本身要有 deadline：慢初始化不能把 /api/status 拖到无限等待。

    用真实 socket 服务器（而不是 MockTransport，后者不实现 httpx 超时语义）
    校验 read 超时确实会触发，并且分层检查共用总预算而不是层层各自耗尽。
    """
    import http.server
    import threading

    class _SlowHandler(http.server.BaseHTTPRequestHandler):
        def do_GET(self):  # noqa: N802
            time.sleep(30)
            body = b'{"ok": true}'
            self.send_response(200)
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, *args):
            pass

    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), _SlowHandler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        port = server.server_address[1]
        monkeypatch.setattr(webui, "supervisorctl", _fake_supervisorctl())
        for key in ("lx_url", "musicdl_url", "musicbox_url"):
            monkeypatch.setitem(webui.CONF, key, f"http://127.0.0.1:{port}")
        real_client = httpx.AsyncClient()
        monkeypatch.setattr(webui, "get_http", lambda *args, **kwargs: real_client)
        started = time.monotonic()
        health = client.get("/api/status").json()["health"]
        elapsed = time.monotonic() - started
        assert elapsed < 8, f"分段健康检查需有界，实际 {elapsed:.1f}s"
        assert health["http"]["ok"] is False
        assert health["http"]["error_type"] == "timeout"
    finally:
        server.shutdown()
        server.server_close()
